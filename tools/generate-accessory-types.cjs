'use strict';

const { writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { init } = require('../lib/CMD4_DEVICE_TYPE_ENUM');

// Only device names are needed here. Supply placeholders for HAP constants
// so the registry can be initialized outside a running Homebridge instance.
const characteristics = new Proxy({}, { get: () => ({}) });
const { properties } = init({}, {}, characteristics, {});
const types = Object.values(properties).map(device => device.deviceName).sort();

writeFileSync(
   join(__dirname, '../homebridge-ui/public/accessory-types.js'),
   '// Generated by npm run generate:accessory-types.\n' +
   'const cmd4AccessoryTypes = ' + JSON.stringify(types, null, 2) + ';\n'
);
